function ReportTable({ title, head, rows }: { title: string; head: string[]; rows: (string | number)[][] }) {
  return (
    <div className="rounded-xl border bg-card shadow-card">
      <div className="border-b p-4"><p className="text-sm font-semibold">{title}</p></div>
      <div className="overflow-x-auto">
        <table className="w-full text-sm">
          <thead className="bg-muted/40 text-xs uppercase tracking-wider text-muted-foreground">
            <tr>{head.map((h, i) => (<th key={i} className={`px-4 py-2.5 font-medium ${i === 0 ? "text-left" : "text-right"}`}>{h}</th>))}</tr>
          </thead>
          <tbody className="divide-y">
            {rows.map((r, ri) => (
              <tr key={ri} className="hover:bg-muted/30">
                {r.map((cell, ci) => (<td key={ci} className={`px-4 py-2.5 ${ci === 0 ? "text-left font-medium text-foreground" : "text-right tabular-nums"}`}>{cell}</td>))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

