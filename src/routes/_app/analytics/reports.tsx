const lossBreakdown = [
  { name: "Physical Leakage", value: 6.4, color: "var(--color-critical)" },
  { name: "Apparent (metering)", value: 4.8, color: "var(--color-warning)" },
  { name: "Unauthorized Use", value: 2.1, color: "var(--color-accent)" },
  { name: "Authorized Unbilled", value: 1.5, color: "var(--color-muted-foreground)" },
];

function buildReportPayload(key: ReportKey, label: string, desc: string, filters: Record<string, string>) {
  const meta = { ...filters, Generated: new Date().toLocaleString("en-IN") };
  const common = { title: label, subtitle: desc, meta, filename: `${label}_${Date.now()}` };

  if (key === "billing-summary") {
    return { ...common, sections: [
      { heading: "Summary", paragraph: `${formatNumber(billingInsightsKpis.billsGenerated.value)} bills generated for ${formatCurrency(billingInsightsKpis.totalBilled.value)} with ${billingInsightsKpis.billingAccuracy.value}% accuracy. ${billingInsightsKpis.billingExceptions.value} exceptions recorded.` },
      { heading: "Monthly Billing Trend", table: { head: ["Month", "Billed (₹ Cr)", "Exceptions"], body: monthlyBillingTrend.map((r) => [r.month, r.billed.toFixed(2), r.exceptions]) } },
      { heading: "Bills Generated by Month", table: { head: ["Month", "Bills"], body: billsGeneratedByMonth.map((r) => [r.month, r.bills]) } },
    ] };
  }
  if (key === "consumption-analysis") {
    return { ...common, sections: [
      { heading: "Summary", paragraph: `Total ${formatNumber(consumptionKpis.total.value)} KL · Avg ${consumptionKpis.average.value} KL/consumer · ${consumptionKpis.highConsumers.value} high consumers · ${consumptionKpis.zeroConsumers.value} zero consumption.` },
      { heading: "Monthly Consumption", table: { head: ["Month", "Domestic (KL)", "Commercial (KL)", "Common (KL)"], body: consumptionTrend.map((r) => [r.month, r.domestic, r.commercial, r.common]) } },
      { heading: "Consumption by Category", table: { head: ["Category", "Consumption (KL)"], body: consumptionByCategory.map((r) => [r.name, r.value]) } },
    ] };
  }
  if (key === "billing-exception") {
    return { ...common, sections: [
      { heading: "Summary", paragraph: `${billingExceptionAnalysis.reduce((a, b) => a + b.count, 0)} billing exceptions across ${billingExceptionAnalysis.length} categories.` },
      { heading: "Exception Analysis", table: { head: ["Exception Type", "Count"], body: billingExceptionAnalysis.map((r) => [r.type, r.count]) } },
    ] };
  }
  if (key === "high-consumption") {
    return { ...common, sections: [
      { heading: "Summary", paragraph: `${highConsumptionConsumers.length} consumers flagged with abnormally high usage this cycle.` },
      { heading: "Top High-Usage Consumers", table: { head: ["Consumer", "Township", "Category", "Consumption (KL)", "Billed"], body: highConsumptionConsumers.map((r) => [r.name, r.township, r.category, r.consumption, formatCurrency(r.amount)]) } },
    ] };
  }
  if (key === "revenue") {
    return { ...common, sections: [
      { heading: "Summary", paragraph: `Total billed ${formatCurrency(48_72_30_000)}; outstanding ${formatCurrency(3_84_12_500)}.` },
      { heading: "Billed (last 6 months)", table: { head: ["Month", "Billed (₹ Cr)", "Outstanding (₹ Cr)"], body: revenueTrend.slice(-6).map((r) => [r.month, r.revenue.toFixed(2), r.outstanding.toFixed(2)]) } },
      { heading: "Township Comparison", table: { head: ["Township", "Revenue (₹ L)", "Consumption (KL)"], body: townshipComparison.map((t) => [t.name, t.revenue, t.consumption]) } },
    ] };
  }
  if (key === "consumption") {
    return { ...common, sections: [
      { heading: "Monthly Consumption", table: { head: ["Month", "Domestic (KL)", "Commercial (KL)", "Common (KL)"], body: consumptionTrend.map((r) => [r.month, r.domestic, r.commercial, r.common]) } },
    ] };
  }
  if (key === "water-loss") {
    return { ...common, sections: [
      { heading: "Loss Breakdown", table: { head: ["Category", "Loss %"], body: lossBreakdown.map((r) => [r.name, r.value]) } },
    ] };
  }
  return { ...common, sections: [
    { heading: "Fleet Health", table: { head: ["Status", "Count"], body: meterHealth.map((m) => [m.name, m.value]) } },
    { heading: "Read Success (last 14 days)", table: { head: ["Day", "Success %"], body: readSuccessTrend.map((r) => [r.day, r.success]) } },
  ] };
}

function Page() {
  const [report, setReport] = useState<ReportKey>("billing-summary");
  const [township, setTownship] = useState<string>("all");
  const [category, setCategory] = useState<string>("all");
  const [cycle, setCycle] = useState<string>("all");
  const [from, setFrom] = useState<string>("2025-01-01");
  const [to, setTo] = useState<string>("2025-11-30");

  const meta = useMemo(() => REPORTS.find((r) => r.key === report)!, [report]);
  const townshipLabel = township === "all" ? "All townships" : townships.find((t) => t.id === township)?.name ?? "All townships";
  const filters = {
    "Date Range": `${from} → ${to}`,
    Township: townshipLabel,
    "Consumer Category": category === "all" ? "All categories" : category,
    "Billing Cycle": cycle === "all" ? "All cycles" : cycle,
  };

  const handleExport = () => {
    downloadPdfReport(buildReportPayload(report, meta.label, meta.desc, filters));
    toast.success(`${meta.label} downloaded as PDF`);
  };

  return (
    <>
      <PageHeader
        title="Reports"
        description="Generate billing, consumption and operational reports with flexible filters."
        actions={
          <>
            <Button variant="outline" size="sm" onClick={handleExport}>
              <Download className="mr-1.5 h-4 w-4" /> Download PDF
            </Button>
            <Button size="sm" onClick={() => toast.success(`${meta.label} sent to recipients`)}>
              <FileText className="mr-1.5 h-4 w-4" /> Send now
            </Button>
          </>
        }
      />

      <div className="mb-6 rounded-xl border bg-card p-4 shadow-card">
        <div className="grid gap-3 md:grid-cols-3 lg:grid-cols-6">
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">Report</label>
            <Select value={report} onValueChange={(v) => setReport(v as ReportKey)}>
              <SelectTrigger><SelectValue /></SelectTrigger>
              <SelectContent>
                {REPORTS.map((r) => (<SelectItem key={r.key} value={r.key}>{r.label}</SelectItem>))}
              </SelectContent>
            </Select>
          </div>
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">From</label>
            <Input type="date" value={from} onChange={(e) => setFrom(e.target.value)} />
          </div>
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">To</label>
            <Input type="date" value={to} onChange={(e) => setTo(e.target.value)} />
          </div>
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">Township</label>
            <Select value={township} onValueChange={setTownship}>
              <SelectTrigger><SelectValue /></SelectTrigger>
              <SelectContent>
                <SelectItem value="all">All townships</SelectItem>
                {townships.map((t) => (<SelectItem key={t.id} value={t.id}>{t.name}</SelectItem>))}
              </SelectContent>
            </Select>
          </div>
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">Consumer Category</label>
            <Select value={category} onValueChange={setCategory}>
              <SelectTrigger><SelectValue /></SelectTrigger>
              <SelectContent>
                <SelectItem value="all">All categories</SelectItem>
                {consumerCategories.map((c) => (<SelectItem key={c} value={c}>{c}</SelectItem>))}
              </SelectContent>
            </Select>
          </div>
          <div>
            <label className="mb-1 block text-xs font-medium text-muted-foreground">Billing Cycle</label>
            <Select value={cycle} onValueChange={setCycle}>
              <SelectTrigger><SelectValue /></SelectTrigger>
              <SelectContent>
                <SelectItem value="all">All cycles</SelectItem>
                {billingCycles.map((c) => (<SelectItem key={c} value={c}>{c}</SelectItem>))}
              </SelectContent>
            </Select>
          </div>
        </div>
      </div>

      <div className="mb-4">
        <h2 className="text-lg font-semibold text-foreground">{meta.label}</h2>
        <p className="text-xs text-muted-foreground">{meta.desc} · {townshipLabel} · {from} → {to}</p>
      </div>

      {report === "billing-summary" && <BillingSummaryReport />}
      {report === "consumption-analysis" && <ConsumptionAnalysisReport />}
      {report === "billing-exception" && <BillingExceptionReport />}
      {report === "high-consumption" && <HighConsumptionReport />}
      {report === "revenue" && <RevenueReport />}
      {report === "consumption" && <ConsumptionReport />}
      {report === "water-loss" && <WaterLossReport />}
      {report === "meters" && <MetersReport />}
    </>
  );
}

